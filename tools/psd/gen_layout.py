#!/usr/bin/env python3
"""Turns the moves made in the edited PSDs into src/menus_layout.h: offset, scale and rotation per text layer."""
import json, math, os, sys
import numpy as np
from PIL import Image
from psd_tools import PSDImage
B = "assets/reimagined/psd"
SCREENS = ["main", "single", "coop", "coopwifi", "charselect", "pause_solo", "gameover", "newgame", "quitconfirm", "savequit", "leavecoop", "reconnectconfirm", "name_editor"]


def axis(im):
    a = np.asarray(im.convert("RGBA").getchannel("A"), dtype=float) > 128
    ys, xs = np.nonzero(a)
    if len(xs) < 8:
        return 0.0
    c = np.cov(xs, ys)
    return 0.5 * math.degrees(math.atan2(2 * c[0, 1], c[0, 0] - c[1, 1]))


m = json.load(open(f"{B}/layers.json"))
out = ["/* Generated by tools/psd/gen_layout.py from the edited PSDs. Logical units, degrees (positive = clockwise). */",
       "static const struct layout_adj { const char *screen, *layer; float dx, dy, scale, deg; } k_layout[] = {"]
for n in SCREENS:
    known = {l["name"]: l for l in m["screens"][n]["layers"]}
    for l in PSDImage.open(f"{B}/psd/{n}.psd").descendants():
        k = known.get(l.name)
        if l.is_group() or not k or k["group"] != "TEXT" or not l.width or not l.height or l.kind != "pixel":
            continue
        ox, oy, ow, oh = k["psd_rect"]
        if [l.left, l.top, l.width, l.height] == [ox, oy, ow, oh]:
            continue
        safe = "".join(c if c.isalnum() else "_" for c in k["group"] + "__" + k["name"]) + ".png"
        deg = axis(l.topil()) - axis(Image.open(f"{B}/layers/{n}/{safe}"))
        deg = 0.0 if abs(deg) < 1 else deg
        scale = 1.0 if abs(deg) >= 1 else round(l.width / ow, 3)
        scale = 1.0 if abs(scale - 1) < .02 else scale
        dx, dy = (l.left + l.width / 2 - ox - ow / 2) / 1.5, (l.top + l.height / 2 - oy - oh / 2) / 1.5
        out.append(f'    {{"{n}", "{k["name"]}", {dx:.2f}f, {dy:.2f}f, {scale:.3f}f, {deg:.2f}f}},')
out.append("};")
open("src/menus_layout.h", "w").write("\n".join(out) + "\n")
print("\n".join(out))
