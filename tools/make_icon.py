"""Builds the game icon from call-of-duty-black-ops-zombies-icon.png (an iOS-style capture with
a grey bevel and black corners): keeps only the red artwork, squares it by extending the plain
red top/bottom edges (no crop into the logo), upscales to 512 px with light sharpening and
applies clean transparent rounded corners.

Writes assets/icon/codboz-pc.png (512), assets/icon/codboz-pc-{48..192}.png (Android sizes)
and src/icon_data.h (64 px RGBA for SDL_SetWindowIcon).
Run: python3 -I tools/make_icon.py
"""
import os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "call-of-duty-black-ops-zombies-icon.png")
INNER = (17, 33, 429, 415)   # red artwork inside the grey bevel


def build(size=512):
    art = Image.open(SRC).convert("RGB").crop(INNER)
    w, h = art.size
    pad = (w - h) // 2
    sq = Image.new("RGB", (w, w))
    sq.paste(art, (0, pad))
    # extend the plain red edges instead of cropping into the logo
    top = art.crop((0, 0, w, 1)).resize((w, pad))
    bot = art.crop((0, h - 1, w, h)).resize((w, w - h - pad))
    sq.paste(top, (0, 0))
    sq.paste(bot, (0, pad + h))
    sq = sq.filter(ImageFilter.GaussianBlur(0.35))            # soften the source JPEG blocks
    big = sq.resize((size * 2, size * 2), Image.LANCZOS)
    big = big.filter(ImageFilter.UnsharpMask(radius=2.2, percent=90, threshold=2))
    big = big.resize((size, size), Image.LANCZOS)
    # safe margin: the logo touches the sides, so shrink it onto a blurred copy of its own red background
    inner = int(size * 0.86)
    # own red background: colours sampled from plain areas of the art, radial falloff like the original
    centre = big.crop((size // 2 - 20, int(size * 0.08), size // 2 + 20, int(size * 0.14))).resize((1, 1), Image.BOX).getpixel((0, 0))
    rim = big.crop((int(size * 0.05), int(size * 0.85), int(size * 0.15), int(size * 0.92))).resize((1, 1), Image.BOX).getpixel((0, 0))
    g = Image.radial_gradient("L").resize((size, size), Image.LANCZOS)   # 0 centre -> 255 rim
    bg = Image.composite(Image.new("RGB", (size, size), rim), Image.new("RGB", (size, size), centre), g)
    fg = big.resize((inner, inner), Image.LANCZOS)
    feather = Image.new("L", (inner, inner), 0)
    m = int(inner * 0.04)
    ImageDraw.Draw(feather).rounded_rectangle((m, m, inner - 1 - m, inner - 1 - m), radius=int(inner * 0.12), fill=255)
    feather = feather.filter(ImageFilter.GaussianBlur(m * 0.8))
    off = (size - inner) // 2
    bg.paste(fg, (off, off), feather)
    big = bg
    mask = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=int(size * 4 * 0.18), fill=255)
    build.square, build.colours = big.copy(), (centre, rim)
    out = big.convert("RGBA")
    out.putalpha(mask.resize((size, size), Image.LANCZOS))
    return out


def main():
    icon = build()
    d = os.path.join(ROOT, "assets", "icon")
    os.makedirs(d, exist_ok=True)
    icon.save(os.path.join(d, "codboz-pc.png"))
    for s in (36, 48, 72, 96, 144, 192):
        icon.resize((s, s), Image.LANCZOS).save(os.path.join(d, "codboz-pc-%d.png" % s))
    # Android TV banner (320x180): full-bleed red, logo centred, rendered at 4x then reduced
    centre, rim = build.colours
    W, H = 1280, 720
    g = Image.radial_gradient("L").resize((W, W), Image.LANCZOS).crop((0, (W - H) // 2, W, (W + H) // 2))
    banner = Image.composite(Image.new("RGB", (W, H), rim), Image.new("RGB", (W, H), centre), g)
    L = int(H * 1.3)   # bigger logo; what spills over vertically is plain red
    logo = build.square.resize((L, L), Image.LANCZOS)
    feather = Image.new("L", (L, L), 0)
    ImageDraw.Draw(feather).rounded_rectangle((50, 50, L - 51, L - 51), radius=110, fill=255)
    banner.paste(logo, ((W - L) // 2, (H - L) // 2), feather.filter(ImageFilter.GaussianBlur(36)))
    banner.resize((320, 180), Image.LANCZOS).save(os.path.join(d, "banner-320x180.png"))
    data = icon.resize((64, 64), Image.LANCZOS).tobytes()
    with open(os.path.join(ROOT, "src", "icon_data.h"), "w") as f:
        f.write("/* generated by tools/make_icon.py */\n#define ICON_W 64\n#define ICON_H 64\n")
        f.write("static const unsigned char g_icon_rgba[] = {\n")
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
